#!/usr/bin/env node
// Writes THIRD_PARTY_LICENSES.md from `cargo metadata` (the crates in the build graph of the workspace) and
// the lockfile of the web app (production packages). Licences are the declared SPDX expressions, not a legal review.
//   node tools/gen_third_party.mjs > THIRD_PARTY_LICENSES.md
import { execFileSync } from 'node:child_process';
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const meta = JSON.parse(execFileSync('cargo', ['metadata', '--offline', '--format-version', '1', '--filter-platform', 'wasm32-unknown-unknown'], { cwd: root, maxBuffer: 1 << 28 }).toString());
const metaNative = JSON.parse(execFileSync('cargo', ['metadata', '--offline', '--format-version', '1', '--filter-platform', 'aarch64-apple-darwin'], { cwd: root, maxBuffer: 1 << 28 }).toString());
const members = new Set(meta.workspace_members);
const byId = new Map();
for (const m of [meta, metaNative]) {
    const reach = new Set();
    const nodes = new Map(m.resolve.nodes.map(n => [n.id, n]));
    const walk = (id) => { if (reach.has(id)) return; reach.add(id); for (const d of nodes.get(id)?.deps ?? []) if (d.dep_kinds.some(k => k.kind !== 'dev')) walk(d.pkg); };
    for (const id of m.workspace_members) walk(id);
    for (const p of m.packages) if (reach.has(p.id) && !members.has(p.id)) byId.set(`${p.name}@${p.version}`, p);
}
const crates = [...byId.values()].sort((a, b) => a.name.localeCompare(b.name));

// npm: production packages of the web workspace, from package-lock.json plus each package's own manifest.
const lock = JSON.parse(readFileSync(join(root, 'web/package-lock.json'), 'utf8'));
// Installed but kept out of the build: Mermaid's optional elk layout (EPL-2.0) is replaced by a stub (vite.config.ts).
const NOT_SHIPPED = new Set(['elkjs']);
// Packages whose manifest declares no licence, with the one in their LICENSE file.
const LICENSE_FILE = { khroma: 'MIT' };
const npm = [];
for (const [path, info] of Object.entries(lock.packages)) {
    if (!path.includes('node_modules/') || info.dev || info.link) continue;
    const name = path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length);
    if (NOT_SHIPPED.has(name)) continue;
    const mf = join(root, 'web', path, 'package.json');
    const lic = info.license ?? (existsSync(mf) ? JSON.parse(readFileSync(mf, 'utf8')).license : undefined) ?? LICENSE_FILE[name] ?? 'UNKNOWN';
    npm.push({ name, version: info.version, license: typeof lic === 'string' ? lic : JSON.stringify(lic) });
}
npm.sort((a, b) => a.name.localeCompare(b.name));

const PERMISSIVE = /^(MIT|Apache-2\.0|BSD-2-Clause|BSD-3-Clause|ISC|Zlib|Unicode-3\.0|Unicode-DFS-2016|0BSD|CC0-1\.0|Unlicense|BSL-1\.0|MIT-0|OFL-1\.1|CDLA-Permissive-2\.0)$/;
const parts = (l) => l.replace(/[()]/g, ' ').split(/\s+(?:OR|AND|WITH)\s+|\s*\/\s*/).map(s => s.trim()).filter(Boolean);
// An OR expression is fine when one alternative is permissive; an AND needs all of them.
function ok(l) {
    if (/ OR /.test(l)) return l.split(/ OR /).some(p => ok(p.replace(/[()]/g, '').trim()));
    return parts(l).every(p => PERMISSIVE.test(p) || p === 'LLVM-exception');
}
const flagged = [...crates.map(c => ({ kind: 'crate', name: c.name, version: c.version, license: c.license ?? 'UNKNOWN' })), ...npm.map(n => ({ kind: 'npm', ...n }))].filter(x => !ok(x.license));

const out = [];
out.push('# Third-party licences', '');
out.push('Generated by `tools/gen_third_party.mjs` from `cargo metadata` and `web/package-lock.json`. The licences are the');
out.push('declared SPDX expressions of each package, not a legal review. Development-only packages are left out.', '');
out.push('## Not plain MIT, Apache, BSD or ISC', '');
if (flagged.length) { out.push('| Kind | Package | Version | Declared licence |', '| --- | --- | --- | --- |'); for (const f of flagged) out.push(`| ${f.kind} | ${f.name} | ${f.version} | ${f.license} |`); }
else out.push('None.');
if (flagged.some(f => /MPL/.test(f.license))) out.push('', 'MPL-2.0 is file-level copyleft: the licence applies to the files of that package, and is compatible with distributing this project under MIT as long as those files stay under MPL-2.0 and their source is available.', '');
else out.push('');
const tally = (list) => { const t = new Map(); for (const x of list) t.set(x.license, (t.get(x.license) ?? 0) + 1); return [...t].sort((a, b) => b[1] - a[1]); };
out.push(`## Rust crates in the build graph (${crates.length})`, '', '| Licence | Count |', '| --- | --- |');
for (const [l, n] of tally(crates.map(c => ({ license: c.license ?? 'UNKNOWN' })))) out.push(`| ${l} | ${n} |`);
out.push('', '| Crate | Version | Licence |', '| --- | --- | --- |');
for (const c of crates) out.push(`| ${c.name} | ${c.version} | ${c.license ?? 'UNKNOWN'} |`);
out.push('', `## npm packages in the web app (${npm.length}, production)`, '', '| Licence | Count |', '| --- | --- |');
for (const [l, n] of tally(npm)) out.push(`| ${l} | ${n} |`);
out.push('', '| Package | Version | Licence |', '| --- | --- | --- |');
for (const n of npm) out.push(`| ${n.name} | ${n.version} | ${n.license} |`);
out.push('', '## Bundled files with their own licence', '');
out.push('* `web/calcpad-web/public/fonts/` JuliaMono (see `JuliaMono-LICENSE`).');
out.push('* `web/calcpad-web/public/report-fonts/` Jost, DejaVu Sans and DejaVu Serif, and the CalcpadCE vector font (each with its `-LICENSE` file).');
out.push('* `web/calcpad-web/public/ui-assets/` jspreadsheet CE and jsuites (MIT; see `README.md` there).');
out.push('* `web/calcpad-web/public/samples/` the CalcpadCE example worksheets (MIT; see `NOTICE.md` there).');
out.push('* `web/calcpad-web/public/py/` MicroPython (MIT, v1.24.1; see `NOTICE.md` there) and the numpy and matplotlib stand-ins for `#python` blocks.');
out.push('* `calcpad-core/src/markdig/` a port of part of Markdig (BSD 2-Clause; see `NOTICE`).');
out.push('', '## MicroPython (bundled runtime for `#python` blocks)', '');
out.push('`web/calcpad-web/public/py/micropython/` holds MicroPython v1.24.1 (build dated 2024-11-30, the version string inside the wasm)');
out.push('compiled to WebAssembly, with its JavaScript loader (which carries Emscripten\'s runtime glue, MIT or University of Illinois/NCSA).');
out.push('Upstream: https://github.com/micropython/micropython. Licence: MIT. The text is also in `public/py/micropython/LICENSE`.', '', '```');
out.push(readFileSync(new URL('../web/calcpad-web/public/py/micropython/LICENSE', import.meta.url), 'utf8').trimEnd(), '```');
console.log(out.join('\n'));
