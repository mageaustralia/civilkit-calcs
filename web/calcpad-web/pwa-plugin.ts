import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import type { Plugin } from 'vite';
import { resolveVersion } from '../version.mjs';

/** Every file of the build, as paths relative to the output folder. */
function walk(dir: string, root: string, out: string[] = []): string[] {
    for (const name of readdirSync(dir)) {
        const full = join(dir, name);
        if (statSync(full).isDirectory()) walk(full, root, out);
        else out.push(relative(root, full).split('\\').join('/'));
    }
    return out;
}

const SW = (version: string, files: string[]) => `// Generated by pwa-plugin.ts at build time. Do not edit.
const CACHE = 'calcs-${version}';
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (e) => {
    // Paths are relative to this file, so the app works under any base.
    e.waitUntil((async () => {
        const cache = await caches.open(CACHE);
        await Promise.all(FILES.map((f) => cache.add(new Request(f, { cache: 'reload' })).catch(() => {})));
        await self.skipWaiting();
    })());
});

self.addEventListener('activate', (e) => {
    e.waitUntil((async () => {
        for (const k of await caches.keys()) if (k.startsWith('calcs-') && k !== CACHE) await caches.delete(k);
        await self.clients.claim();
    })());
});

self.addEventListener('fetch', (e) => {
    const req = e.request;
    if (req.method !== 'GET' || req.headers.has('range')) return;
    const url = new URL(req.url);
    if (url.origin !== location.origin && !/^(cdn\\.plot\\.ly|cdn\\.jsdelivr\\.net|cdnjs\\.cloudflare\\.com|unpkg\\.com)$/.test(url.hostname)) return;
    e.respondWith((async () => {
        const cache = await caches.open(CACHE);
        const hit = await cache.match(req, { ignoreSearch: url.origin === location.origin });
        if (hit) return hit;
        try {
            const res = await fetch(req);
            if (res.ok) cache.put(req, res.clone());
            return res;
        } catch (err) {
            if (req.mode === 'navigate') {
                const page = await cache.match(new URL('index.html', location.href).href);
                if (page) return page;
            }
            throw err;
        }
    })());
});
`;

/** Writes sw.js beside index.html: it precaches the whole build so the app opens offline.
 *  The static What's new page (whats-new/, with its clips), the landing pages (learn/), the language catalogues (i18n/), sitemap.xml, robots.txt and llms.txt are for
 *  readers and crawlers and are left out of the precache: their requests go to the network, so a visit always gets the
 *  page itself, never the app. */
export function pwaPlugin(): Plugin {
    let outDir = 'dist';
    return {
        name: 'pwa-sw',
        apply: 'build',
        configResolved(c) { outDir = resolve(c.root, c.build.outDir); },
        closeBundle() {
            const files = walk(outDir, outDir).filter((f) => f !== 'sw.js' && !f.startsWith('whats-new/') && !f.startsWith('learn/') && !f.startsWith('i18n/') && f !== 'sitemap.xml' && f !== 'robots.txt' && !f.startsWith('llms') && !f.endsWith('.map') && !f.endsWith('.stub'));
            // The cache name follows the content, so a rebuild at the same version still refreshes it.
            const hash = createHash('sha1');
            for (const f of files) hash.update(f).update(readFileSync(join(outDir, f)));
            // The language catalogues (i18n/) are fetched when a language is used, not installed, but a changed one still renews the cache.
            for (const f of walk(outDir, outDir).filter((f) => f.startsWith('i18n/'))) hash.update(f).update(readFileSync(join(outDir, f)));
            const index = files.indexOf('index.html');
            if (index >= 0) files[index] = './';
            writeFileSync(join(outDir, 'sw.js'), SW(`${resolveVersion()}-${hash.digest('hex').slice(0, 8)}`, files));
        },
    };
}
