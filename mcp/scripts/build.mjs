// Prepares mcp/src/generated (git ignored) from the repository, so the Worker bundles exactly what the app ships:
//   calcpad_wasm_bg.wasm, calcpad_sheet_wasm_bg.wasm   the engine and the sheet compiler, copied from the app's
//                                                      public/wasm (tools/build_wasm.sh), with a memory maximum added
//   engine_glue.js, sheet_glue.js                      the wasm-bindgen glue of those modules, turned into factories
//                                                      that make a fresh instance per call (see src/engine.js)
//   data.js                                            the guide chapters, the sheet samples, the function reference
//                                                      (the highlighter's snippets.json) and docs/sheet-syntax.md
//   meta.js                                            versions and sizes
//
//   node scripts/build.mjs            build
//   WASM_DIR=/path node scripts/build.mjs   take the wasm from another folder
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..');
const out = join(here, '..', 'src', 'generated');
const pub = join(root, 'web', 'calcpad-web', 'public');
const wasmDir = resolve(process.env.WASM_DIR ?? join(pub, 'wasm'));
mkdirSync(out, { recursive: true });

// Memory caps (64 KiB pages). A Worker isolate has 128 MB for JavaScript and every wasm memory together; a module
// without a maximum would grow until the isolate is killed. With a maximum, a run that needs more fails inside the
// engine (an allocation failure traps) and the request gets a clean error.
export const ENGINE_MAX_PAGES = 1024; // 64 MiB
export const SHEET_MAX_PAGES = 256; // 16 MiB

function leb(bytes, p) {
    let r = 0, s = 0, b;
    do { b = bytes[p++]; r += (b & 0x7f) * 2 ** s; s += 7; } while (b & 0x80);
    return [r, p];
}
function uleb(n) {
    const a = [];
    do { let b = n & 0x7f; n = Math.floor(n / 128); if (n) b |= 0x80; a.push(b); } while (n);
    return a;
}

/** The module with its one defined memory given a maximum of `maxPages` (the memory section is rewritten). */
export function capMemory(bytes, maxPages) {
    if (bytes.readUInt32LE(0) !== 0x6d736100) throw new Error('not a wasm module');
    let p = 8;
    while (p < bytes.length) {
        const start = p;
        const id = bytes[p++];
        const [size, q] = leb(bytes, p);
        const body = q;
        p = q + size;
        if (id !== 5) continue;
        const [count, r] = leb(bytes, body);
        if (count !== 1) throw new Error(`expected one memory, found ${count}`);
        const flag = bytes[r];
        if (flag !== 0 && flag !== 1) throw new Error(`unexpected memory flags ${flag}`);
        const [min] = leb(bytes, r + 1);
        if (min > maxPages) throw new Error(`initial memory ${min} pages is above the cap ${maxPages}`);
        const section = [...uleb(1), 1, ...uleb(min), ...uleb(maxPages)];
        return Buffer.concat([bytes.subarray(0, start), Buffer.from([5, ...uleb(section.length), ...section]), bytes.subarray(p)]);
    }
    throw new Error('no memory section');
}

/**
 * wasm-bindgen's `--target web` glue keeps the instance in module variables, so it can only be initialised once.
 * Wrapped in a function it makes a new instance per call: no state survives from one request to the next, and an
 * instance that trapped is simply dropped. The async loader (which could fetch) is cut out; the host import that
 * would reach for the highlighter is a local function that throws (the engine then lists code unhighlighted).
 */
export function factory(glue, name, exportsList) {
    let src = glue;
    const must = (re, to, what) => {
        if (!re.test(src)) throw new Error(`${name}: wasm-bindgen glue changed (${what}); update scripts/build.mjs`);
        src = src.replace(re, to);
    };
    must(/^export function /gm, 'function ', 'exported functions');
    must(/^export \{ initSync, __wbg_init as default \};\s*$/m, '', 'export list');
    // The async init path (fetch of a URL) is not used; remove it so the bundle has no network call.
    must(/async function __wbg_load\([\s\S]*?\n}\n/, '', '__wbg_load');
    must(/async function __wbg_init\([\s\S]*?\n}\n/, '', '__wbg_init');
    if (/\bfetch\(|import\.meta/.test(src)) throw new Error(`${name}: glue still has fetch or import.meta`);
    const host = /calcpadTokenizeListing\(/.test(src)
        ? "    function calcpadTokenizeListing() { throw new Error('no highlighter in this build'); }\n"
        : '';
    return `// Generated by mcp/scripts/build.mjs from ${name}.js (wasm-bindgen). Do not edit.\n`
        + `export function create(compiledModule) {\n${host}${src.replace(/^/gm, '    ')}\n`
        + `    initSync({ module: compiledModule });\n`
        + `    return { ${exportsList.join(', ')}, memory: () => wasm.memory };\n}\n`;
}

function buildWasm() {
    const sizes = {};
    for (const [m, max, exportsList] of [
        ['calcpad_wasm', ENGINE_MAX_PAGES, ['convert', 'version']],
        ['calcpad_sheet_wasm', SHEET_MAX_PAGES, ['compile', 'format', 'is_sheet']],
    ]) {
        const wasmPath = join(wasmDir, `${m}_bg.wasm`);
        const gluePath = join(wasmDir, `${m}.js`);
        if (!existsSync(wasmPath) || !existsSync(gluePath)) {
            console.error(`No ${m} in ${wasmDir}. Run tools/build_wasm.sh (engine, sheet) or set WASM_DIR.`);
            process.exit(2);
        }
        const capped = capMemory(readFileSync(wasmPath), max);
        new WebAssembly.Module(capped); // still valid
        writeFileSync(join(out, `${m}_bg.wasm`), capped);
        const glueName = m === 'calcpad_wasm' ? 'engine_glue.js' : 'sheet_glue.js';
        writeFileSync(join(out, glueName), factory(readFileSync(gluePath, 'utf8'), m, exportsList));
        sizes[m] = { raw: capped.length, gzip: gzipSync(capped, { level: 9 }).length, sha256: createHash('sha256').update(capped).digest('hex').slice(0, 16) };
    }
    return sizes;
}

// ----- guide ----------------------------------------------------------------------------------------------------

const GUIDE = 'https://civilkit.io/calcs/guide/';

/** 'units.md' -> 'units', 'sheet/index.md' -> 'sheet/', 'introduction.md' -> '' (tools/guide_url.mjs). */
function guidePath(md) {
    const f = md.replace(/^\.?\//, '').replace(/\.(md|html)$/, '');
    if (f === 'introduction' || f === 'index') return '';
    return f.endsWith('/index') ? f.slice(0, -'index'.length) : f;
}

/** mdBook's heading ids (normalize_id): lower case, spaces to '-', only letters, digits, '_' and '-' kept. */
function headingId(text) {
    return text.trim().toLowerCase().replace(/<[^>]+>/g, '').replace(/`/g, '')
        .split('').map((c) => (/\s/.test(c) ? '-' : c)).filter((c) => /[\p{L}\p{N}_-]/u.test(c)).join('');
}

function guide() {
    const chapters = [];
    let section = 'Guide';
    for (const line of readFileSync(join(root, 'book', 'src', 'SUMMARY.md'), 'utf8').split(/\r?\n/)) {
        const h = /^#\s+(.+)$/.exec(line);
        if (h && h[1] !== 'Summary') { section = h[1].trim(); continue; }
        const m = /^\s*[-*]?\s*\[([^\]]+)\]\(([^)]+\.md)\)/.exec(line);
        if (!m) continue;
        const md = readFileSync(join(root, 'book', 'src', m[2]), 'utf8').replace(/\r\n/g, '\n');
        const path = guidePath(m[2]);
        // Sections for search: split at ## and ### headings (not inside code fences).
        const parts = [];
        let cur = { heading: m[1], anchor: '', lines: [] };
        let fence = false;
        for (const l of md.split('\n')) {
            if (/^\s*(```|~~~)/.test(l)) fence = !fence;
            const hh = !fence && /^(#{2,3})\s+(.+?)\s*#*\s*$/.exec(l);
            if (hh) {
                parts.push(cur);
                const title = hh[2].replace(/\s*\{[^}]*\}\s*$/, '');
                cur = { heading: title, anchor: headingId(title), lines: [] };
                continue;
            }
            if (/^#\s/.test(l) && !fence) continue;
            cur.lines.push(l);
        }
        parts.push(cur);
        chapters.push({
            page: path === '' ? 'introduction' : path.replace(/\/$/, ''),
            file: m[2],
            title: m[1],
            section,
            url: GUIDE + path,
            markdown: md,
            sections: parts.map((p) => ({ heading: p.heading, anchor: p.anchor, text: p.lines.join('\n').trim() })).filter((p) => p.text),
        });
    }
    return chapters;
}

// ----- samples --------------------------------------------------------------------------------------------------

function samples() {
    const m = JSON.parse(readFileSync(join(pub, 'sheet-samples', 'manifest.json'), 'utf8'));
    return {
        groups: m.groups,
        samples: m.samples.filter((s) => /\.sheet$/i.test(s.file)).map((s) => ({
            id: s.id,
            title: s.title,
            group: s.group,
            description: s.description,
            file: s.file.replace(/^.*\//, ''),
            inputs: Boolean(s.ui),
            python: false,
            text: readFileSync(join(pub, s.file), 'utf8').replace(/^﻿/, '').replace(/\r\n/g, '\n'),
        })).map((s) => ({ ...s, python: /^\s*```python/m.test(s.text) || /^\s*#python\s*$/m.test(s.text) })),
    };
}

// ----- functions ------------------------------------------------------------------------------------------------

const FUNCTION_KINDS = ['Constant', 'Operator', 'Function', 'VectorFunction', 'MatrixFunction', 'Keyword', 'Command', 'Setting', 'Unit', 'FormatString'];

function functions() {
    const j = JSON.parse(readFileSync(join(root, 'calcpad-highlighter', 'src', 'snippets', 'snippets.json'), 'utf8'));
    const list = [];
    for (const kind of FUNCTION_KINDS) {
        for (const e of j[kind] ?? []) {
            const insert = String(e.Insert ?? '');
            const label = String(e.Label ?? '').trim();
            const base = (label || insert).replace(/§/g, '').trim();
            const name = /^[#$]?[\p{L}_][\p{L}\p{N}_′″‴⁗]*/u.exec(base)?.[0] ?? base.split(/\s+/)[0];
            const params = (e.Parameters ?? []).map((p) => ({ name: p.Name, type: p.Type, description: p.Description }));
            let signature = label && /\(/.test(label) ? label : insert;
            if (/§/.test(signature) && params.length) {
                let k = 0;
                const n = (signature.match(/§/g) ?? []).length;
                signature = n === 1 ? signature.replace('§', params.map((p) => p.name).join('; ')) : signature.replace(/§/g, () => params[k++]?.name ?? '...');
            }
            signature = signature.replace(/§/g, '').trim();
            list.push({
                name,
                kind,
                category: e.Category ?? kind,
                signature,
                insert: insert.replace(/§/g, ''),
                description: e.Description ?? '',
                documentation: e.Documentation ?? '',
                parameters: params,
                returns: e.ReturnTypeDescription ?? e.ReturnType ?? '',
                example: e.Example ?? '',
                elementWise: Boolean(e.IsElementWise),
                acceptsAnyCount: Boolean(e.AcceptsAnyCount),
            });
        }
    }
    return list;
}

// ----- write ----------------------------------------------------------------------------------------------------

function version() {
    const toml = readFileSync(join(root, 'Cargo.toml'), 'utf8');
    return /\[workspace\.package\][^\[]*?\nversion\s*=\s*"([^"]+)"/.exec(toml)?.[1] ?? '0.0.0';
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const sizes = buildWasm();
    const data = {
        guide: guide(),
        samples: samples(),
        functions: functions(),
        syntax: readFileSync(join(root, 'docs', 'sheet-syntax.md'), 'utf8').replace(/\r\n/g, '\n'),
    };
    writeFileSync(join(out, 'data.js'), `// Generated by mcp/scripts/build.mjs. Do not edit.\nexport default ${JSON.stringify(data)};\n`);
    const meta = { version: version(), wasm: sizes, built: 'from the working tree' };
    writeFileSync(join(out, 'meta.js'), `// Generated by mcp/scripts/build.mjs. Do not edit.\nexport default ${JSON.stringify(meta, null, 2)};\n`);
    console.log(`mcp build: ${data.guide.length} guide chapters, ${data.samples.samples.length} sheet samples, ${data.functions.length} reference entries`);
    for (const [k, v] of Object.entries(sizes)) console.log(`  ${k}_bg.wasm ${v.raw} bytes, ${v.gzip} gzipped (memory capped)`);
}
